NOTE = """
**Перевод.** Под третьей строкой — русский перевод: только чтобы понять смысл.
**Размечайте немецкое предложение** (строка `→`), а не перевод.
"""


def main():
    rows = [json.loads(l) for l in open(SET, encoding="utf-8") if l.strip()]
    text = {r["id"]: r["text"] for r in rows}
    missing = [r["id"] for r in rows if r["id"] not in RU]
    if missing:
        print("НЕТ ПЕРЕВОДА:", missing)
        return 2

    lines = open(MD, encoding="utf-8").read().split("\n")
    out, i, done = [], 0, set()
    while i < len(lines):
        m = re.match(r"^\*\*\[([^\]]+)\]\*\*", lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        cid = m.group(1)
        out.append(lines[i])
        i += 1
        # пропускаем пустые строки, затем ожидаем немецкое предложение
        blanks = []
        while i < len(lines) and not lines[i].strip():
            blanks.append(lines[i])
            i += 1
        if i < len(lines):
            out.extend(blanks)
            out.append(text[cid])     # немецкое предложение (из jsonl — эталон)
            i += 1
            # выбрасываем остальное содержимое блока до следующего заголовка
            while i < len(lines) and not lines[i].startswith("**[") and not lines[i].startswith("## "):
                i += 1
            out.append(RU[cid])       # перевод
            out.append("→ " + text[cid])  # дубль для разметки
            out.append("")            # пустая строка между блоками
            done.add(cid)
        continue

    result = "\n".join(out)
    # вставляем пояснение о переводе после блока «Как размечать»
    anchor = "Ориентир: 150 предложений"
    if NOTE.strip() not in result and anchor in result:
        result = result.replace(anchor, NOTE.strip() + "\n\n" + anchor, 1)
    open(MD, "w", encoding="utf-8").write(result)
    print(f"готово: {len(done)} блоков из {len(rows)}; файл {MD}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
